// Helper to generate realistic chart series
export function generateHistory(basePrice: number, changePct: number) {
  const points1D: { time: string; price: number; volume: number }[] = [];
  const hours = ['09:30', '10:30', '11:30', '12:30', '13:30', '14:30', '15:30', '16:00'];
  let currentP = basePrice / (1 + changePct / 100);
  const step = (basePrice - currentP) / (hours.length - 1);
  hours.forEach((h, idx) => {
    const variance = (Math.sin(idx * 1.3) * 0.008 + (Math.random() - 0.5) * 0.004) * basePrice;
    currentP += step + variance;
    points1D.push({
      time: h,
      price: Number(currentP.toFixed(2)),
      volume: Math.round(500000 + Math.random() * 2000000),
    });
  });
  // Ensure last point is exactly basePrice
  if (points1D.length > 0) {
    points1D[points1D.length - 1].price = basePrice;
  }

  const days1W = ['Mon', 'Tue', 'Wed', 'Thu', 'Fri'];
  const points1W = days1W.map((d, i) => ({
    time: d,
    price: Number((basePrice * (0.97 + i * 0.008 + (Math.sin(i) * 0.01))).toFixed(2)),
    volume: Math.round(1500000 + Math.random() * 3000000),
  }));
  points1W[points1W.length - 1].price = basePrice;

  const weeks1M = ['Week 1', 'Week 2', 'Week 3', 'Week 4'];
  const points1M = weeks1M.map((w, i) => ({
    time: w,
    price: Number((basePrice * (0.94 + i * 0.02 + Math.random() * 0.015)).toFixed(2)),
    volume: Math.round(8000000 + Math.random() * 5000000),
  }));
  points1M[points1M.length - 1].price = basePrice;

  const months1Y = ['Jan', 'Mar', 'May', 'Jul', 'Sep', 'Nov', 'Now'];
  const points1Y = months1Y.map((m, i) => ({
    time: m,
    price: Number((basePrice * (0.82 + i * 0.03 + Math.sin(i) * 0.025)).toFixed(2)),
    volume: Math.round(40000000 + Math.random() * 15000000),
  }));
  points1Y[points1Y.length - 1].price = basePrice;

  const yearsALL = ['2020', '2021', '2022', '2023', '2024', '2025', '2026'];
  const pointsALL = yearsALL.map((y, i) => ({
    time: y,
    price: Number((basePrice * (0.45 + i * 0.09 + (i === 2 ? -0.1 : 0.05))).toFixed(2)),
    volume: Math.round(120000000 + Math.random() * 40000000),
  }));
  pointsALL[pointsALL.length - 1].price = basePrice;

  return {
    '1D': points1D,
    '1W': points1W,
    '1M': points1M,
    '1Y': points1Y,
    'ALL': pointsALL,
  };
}

